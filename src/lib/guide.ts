/** Показывать ли walkthrough автоматически (не было пропуска до этого). */
export function shouldAutoOpen(): boolean {
  try {
    return localStorage.getItem(WALKTHROUGH_KEY) == null;
  } catch {
    return true;
  }
}

/** Отметить, что пользователь уже видел/пропустил обзор. */
export function markSeen(): void {
  try {
    localStorage.setItem(WALKTHROUGH_KEY, '1');
  } catch {
    /* noop */
  }
}